// Joins all migrations into one file you can paste into the Supabase SQL Editor on a fresh project.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'supabase', 'migrations')
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const out = ['-- StudyHub: all migrations in order. Paste into the Supabase SQL Editor ONCE on a fresh project.', '-- Generated by scripts/bundle-sql.mjs. Do not edit; edit the files in supabase/migrations/ and regenerate.', '']
for (const f of files) out.push(`-- =====================================================================`, `-- ${f}`, `-- =====================================================================`, fs.readFileSync(path.join(dir, f), 'utf8').trim(), '')
fs.writeFileSync(path.join(root, 'supabase', 'all_migrations.sql'), out.join('\n'))
console.log(`Wrote supabase/all_migrations.sql (${files.length} migrations)`)
